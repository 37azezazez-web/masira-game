  /** يحوّل السطر لخطوط ومواقع على الملعب (x من اليسار ٪، y من فوق ٪) */
  function layout(p) {
    const lines = p.split("|").map((l) => l.split("،").map((n) => n.trim()).filter(Boolean));
    const out = [];
    const n = lines.length;
    lines.forEach((line, li) => {
      // الحارس تحت، والهجوم فوق
      const y = li === 0 ? 89 : 72 - ((li - 1) * 56) / Math.max(1, n - 2);
      line.forEach((name, i) => {
        // أول اسم في الخط على اليمين
        const x = 100 - ((i + 1) * 100) / (line.length + 1);
        const pos = li === 0 ? "حارس" : li === 1 ? "دفاع" : li === n - 1 ? "هجوم" : "وسط";
        out.push({ name, x: Math.round(x), y: Math.round(y), pos });
      });
    });
    return out;
  }

